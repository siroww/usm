// Шаг 5: Переменные и способы вывода
$days = 288;
$message = "Все возвращаются на работу!";

// Способ 1: Использование конкатенации (оператор .)
echo "Прошло " . $days . " дней. " . $message . "<br />";

// Способ 2: Использование двойных кавычек (интерполяция переменных)
echo "Прошло $days дней. $message<br />";
?>

<!-- Ответы на контрольные вопросы
1. Какие способы установки PHP существуют?
Ручная установка (Standalone binary): Скачивание официального архива PHP с php.net, распаковка и ручное добавление пути к исполняемому файлу в системную переменную окружения PATH.

Готовые локальные серверные сборки (XAMPP, Open Server, MAMP, WampServer): Установка единого пакета, включающего веб-сервер (Apache/Nginx), PHP, СУБД (MySQL/MariaDB) и панель управления.

Менеджеры пакетов (Linux / macOS): Установка через системные пакетные менеджеры (apt install php, dnf install php, brew install php).

Контейнеризация (Docker): Использование готовых официальных Docker-образов PHP.


2. Как проверить, что PHP установлен и работает?
Через терминал/командную строку: Выполнить команду php -v. Если PHP установлен корректно, выведется информация о текущей версии интерпретатора.

Через веб-сервер: Создать файл info.php с кодом <?php phpinfo(); ?> и открыть его в браузере. Вывод полной таблицы конфигурации подтвердит работу PHP с веб-сервером.


3. Чем отличается оператор echo от print?
echo 
 Ничего не возвращает (void).
 Может принимать несколько аргументов через запятую: echo "a", "b", "c";
 Работает незначительно быстрее, так как не возвращает значение.

print
 Возвращает значение 1, что позволяет использовать его в выражениях.
 Принимает строго один аргумент.
 Работает чуть медленнее echo. 
